-- Фундамент схемы: справочники (reference tables) сервиса BotBooker.
--
-- Здесь собраны все справочники из ERDB.md, на которые ссылаются бизнес-таблицы
-- (разделы 2.6-2.9, 2.22-2.24): роли, типы объектов, населённые пункты, статусы
-- объектов, а также статусы брони, валюты и способы оплаты. Набор значений
-- держится в одном месте: его проверяет внешний ключ, а расширяется он миграцией,
-- а не правкой CHECK/ENUM сразу в нескольких таблицах.
--
-- Тип PK справочников — целочисленный (SMALLINT/INT, см. соглашения ERDB):
-- значения стабильны, меняются редко и дублируются в контракте строковым кодом
-- (`code`). У справочников с фиксированным набором (roles, statuses,
-- booking_statuses, currencies, payment_methods) id назначены миграцией явно: на
-- них ссылаются DEFAULT у бизнес-таблиц, поэтому соответствие «число -> код»
-- должно быть одинаковым в PostgreSQL и SQLite.
--
-- IF NOT EXISTS не используется: миграция версионирована, а чужая таблица с тем
-- же именем должна ронять старт явной ошибкой, а не подменять схему.

-- Роли (ERDB 2.6): набор стабильный, id фиксированы. `client` (32767) — роль по
-- умолчанию для tenant_members.role_id, поэтому то же значение использует
-- DEFAULT там.
CREATE TABLE roles (
    id        SMALLINT     PRIMARY KEY,
    code      VARCHAR(32)  NOT NULL,
    title     VARCHAR(100) NOT NULL,
    is_active BOOLEAN      NOT NULL DEFAULT true
);

CREATE UNIQUE INDEX roles_code_idx ON roles (code);

-- Типы объектов (ERDB 2.7): значения не заданы заранее (административные),
-- поэтому id — автоинкремент. GENERATED BY DEFAULT AS IDENTITY (а не ALWAYS)
-- оставляет возможность вставить id явно, если потребуется перенос данных.
CREATE TABLE type_objects (
    id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL
);

CREATE UNIQUE INDEX type_objects_title_idx ON type_objects (title);

-- Населённые пункты (ERDB 2.8): часовой пояс хранится здесь (у пункта он один),
-- объект получает его через location_id.
CREATE TABLE locations (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)     NOT NULL,
    type       VARCHAR(50)      NOT NULL,
    region     VARCHAR(100)     NOT NULL,
    population INT,
    lat        DOUBLE PRECISION,
    lon        DOUBLE PRECISION,
    timezone   VARCHAR(64)      NOT NULL,
    created_at TIMESTAMPTZ      NOT NULL,
    updated_at TIMESTAMPTZ      NOT NULL,
    CONSTRAINT locations_population_check CHECK (population IS NULL OR population >= 0),
    CONSTRAINT locations_lat_check CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
    CONSTRAINT locations_lon_check CHECK (lon IS NULL OR lon BETWEEN -180 AND 180)
);

CREATE UNIQUE INDEX locations_name_region_idx ON locations (name, region);

CREATE INDEX locations_region_idx ON locations (region);

-- Статусы объектов аренды (ERDB 2.9): id фиксированы. `active` (1) — статус по
-- умолчанию для rental_objects.status_id, а «мягкое удаление» — это `deleted` (4).
CREATE TABLE statuses (
    id    SMALLINT     PRIMARY KEY,
    code  VARCHAR(20)  NOT NULL,
    title VARCHAR(100) NOT NULL
);

CREATE UNIQUE INDEX statuses_code_idx ON statuses (code);

-- Статусы брони (ERDB 2.22): справочник вместо ENUM у bookings.status_id и
-- bookings_journal.status_id. `pending` (1) — статус новой брони.
CREATE TABLE booking_statuses (
    id        SMALLINT     PRIMARY KEY,
    code      VARCHAR(20)  NOT NULL,
    title     VARCHAR(100) NOT NULL,
    is_active BOOLEAN      NOT NULL DEFAULT true
);

CREATE UNIQUE INDEX booking_statuses_code_idx ON booking_statuses (code);

-- Валюты (ERDB 2.23, ISO-4217): справочник вместо CHAR(3)-кода в бронях и
-- платежах. `RUB` (1) — валюта по умолчанию.
CREATE TABLE currencies (
    id          SMALLINT     PRIMARY KEY,
    code        CHAR(3)      NOT NULL,
    title       VARCHAR(100) NOT NULL,
    symbol      VARCHAR(8)   NOT NULL DEFAULT '',
    minor_units SMALLINT     NOT NULL DEFAULT 2,
    is_active   BOOLEAN      NOT NULL DEFAULT true,
    CONSTRAINT currencies_code_length_check CHECK (char_length(code) = 3),
    CONSTRAINT currencies_minor_units_check CHECK (minor_units >= 0)
);

CREATE UNIQUE INDEX currencies_code_idx ON currencies (code);

-- Способы оплаты (ERDB 2.24): справочник вместо ENUM у payments.payment_method_id.
CREATE TABLE payment_methods (
    id        SMALLINT     PRIMARY KEY,
    code      VARCHAR(20)  NOT NULL,
    title     VARCHAR(100) NOT NULL,
    is_active BOOLEAN      NOT NULL DEFAULT true
);

CREATE UNIQUE INDEX payment_methods_code_idx ON payment_methods (code);

